export function groupOptions(codes: string[]): { title: string; items: string[] }[] {
  const set = new Set(codes);
  return OPTION_GROUPS.map((g) => ({ title: g.title, items: g.codes.filter((c) => set.has(c)).map((c) => OPTION_NAMES[c]!) }))
    .filter((g) => g.items.length);
}
